// This is the small amount of output normally generated by the Typert
// compiler for a standard decorator. Keeping it local lets the plugin remain
// plain JavaScript while still exposing a real Typert Remote service.
const runInitializers = (self, initializers) => {
  for (const initializer of initializers) initializer.call(self);
};

const decorateMethod = (Class, method, decorator) => {
  const initializers = [];
  const descriptor = Object.getOwnPropertyDescriptor(Class.prototype, method);
  decorator(descriptor.value, {
    kind: 'method', name: method, static: false, private: false,
    access: { has: (object) => method in object, get: (object) => object[method] },
    addInitializer(initializer) { initializers.push(initializer); }
  });
  Object.defineProperty(Class.prototype, method, descriptor);
  const Original = Class;
  return class extends Original {
    constructor(...args) {
      super(...args);
      runInitializers(this, initializers);
    }
  };
};

/** Register the Host Remote lazily so unit tests do not need DSH peer packages. */
export async function registerProjectAgentPresetsRemote(ctx) {
  const { Remote, TypertRemoteService } = await import('@deepseek-ai/dsh-typert-protocol');
  class ProjectAgentPresetsRuntimeBase extends TypertRemoteService {
    constructor(owner) {
      super(owner, 'projectAgentPresets');
    }

    async list(agent) {
      const cwd = agent?.session?.header?.cwd;
      return { candidates: await discoverProjectAgentPresets(cwd) };
    }
  }
  const Runtime = decorateMethod(ProjectAgentPresetsRuntimeBase, 'list', Remote('list'));
  return new Runtime(ctx);
}
